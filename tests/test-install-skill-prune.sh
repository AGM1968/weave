#!/usr/bin/env bash
# Suite-driven wv calls are tagged test so call-stats retro reads can exclude them.
export WV_CALL_SOURCE=test
# install.sh prunes CONFIG_DIR skills it no longer ships (wv-f4a68b).
#
# install.sh copied its skills into CONFIG_DIR/skills and never removed one, so
# the five skills the consolidation archived (epic-breakdown, prove-it,
# rubber-duck, stay-in-lane, unstuck) stayed resident on every machine. It now
# records what it installed in skills/.weave-installed and removes a recorded
# skill that has left WV_CONFIG_SKILLS. A skill it never recorded (hand-written,
# or placed by another tool) and a procedure-projected skill (WEAVE-MANAGED-SKILL
# marker) are never removed. A CONFIG_DIR older than the manifest is seeded
# with the skills retired before it existed.
set -uo pipefail
export WV_TEST_SUITE=1  # the user's config.env cannot log this suite's wv calls (wv-6b0f57)
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
run=0; pass=0
ok()  { run=$((run+1)); pass=$((pass+1)); echo "  ✓ $1"; }
bad() { run=$((run+1)); echo "  ✗ $1"; [ -n "${2:-}" ] && echo "      $2"; }
check() { if [ "$2" = "$3" ]; then ok "$1"; else bad "$1" "expected [$2], got [$3]"; fi; }

T=$(bash "$ROOT/scripts/lib/wv-scratch.sh") || exit 1
trap 'rm -rf "$T"' EXIT
mkdir -p "$T/home" "$T/bin" "$T/lib" "$T/config/skills"
# Provenance commands can refresh an index; give them private source and a
# Git discovery boundary, not the checkout another gate reads (wv-6900e1).
mkdir -p "$T/src"
git -C "$ROOT" ls-files -z | (cd "$ROOT" && tar --null -T - --ignore-failed-read -cf - 2>/dev/null) | tar -x -C "$T/src" || exit 1
git -C "$T/src" init -q || exit 1
ROOT="$T/src"
SK="$T/config/skills"
install_here() {
    (cd "$ROOT" && HOME="$T/home" CLAUDE_CONFIG_DIR="$T/home/.claude" WV_INSTALL_DIR="$T/bin" \
        WV_LIB_DIR="$T/lib" WV_CONFIG_DIR="$T/config" bash "$ROOT/install.sh") > "$T/install.log" 2>&1
}
skill() { mkdir -p "$SK/$1"; printf '%s\n' "---" "name: $1" "---" "${2:-}" > "$SK/$1/SKILL.md"; }
present() { [ -d "$SK/$1" ] && echo present || echo absent; }

echo "=== a CONFIG_DIR from before the manifest ==="
skill unstuck                          # archived by the consolidation
skill epic-breakdown
skill my-own-skill "hand-written"      # never installed by install.sh
skill projected "<!-- WEAVE-MANAGED-SKILL: do not edit; regenerated by project-procedures.sh -->"
install_here; rc=$?
check "install.sh succeeds" "0" "$rc"
check "an archived skill is removed" "absent" "$(present unstuck)"
check "every archived skill is removed" "absent" "$(present epic-breakdown)"
check "a hand-written skill is kept" "present" "$(present my-own-skill)"
check "a procedure-projected skill is kept" "present" "$(present projected)"
check "a shipped skill is installed" "present" "$(present trails)"
if grep -qx trails "$SK/.weave-installed" 2>/dev/null; then
    ok "the manifest records what was installed"
else
    bad "the manifest records what was installed" "manifest: $(tr '\n' ' ' < "$SK/.weave-installed" 2>/dev/null)"
fi

echo "=== a skill leaves the shipped set later ==="
skill old-skill
printf 'old-skill\n' >> "$SK/.weave-installed"   # installed by an earlier release
skill still-mine "hand-written, never recorded"
install_here
check "a recorded skill that is no longer shipped is removed" "absent" "$(present old-skill)"
check "an unrecorded skill is still kept" "present" "$(present still-mine)"
check "shipped skills survive the prune" "present" "$(present zero-in)"
if grep -qx old-skill "$SK/.weave-installed"; then
    bad "the manifest drops the removed skill"
else
    ok "the manifest drops the removed skill"
fi

echo "Results: $pass/$run passed"
[ "$pass" -eq "$run" ]
