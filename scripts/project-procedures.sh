#!/usr/bin/env bash
# Project canonical procedure contracts into managed adapter surfaces.
set -euo pipefail

SELF_DIR="$(cd "$(dirname "${BASH_SOURCE[0]:-$0}")" && pwd)"
# The procedures default to the installed set, except when this script runs
# from a Weave checkout (scripts/ beside templates/procedures) with no
# WV_CONFIG_DIR: the checkout's own procedures are then the source. The
# installed copy lags the checkout, and projecting it silently overwrote
# checkout edits (wv-720adc; wrong-copy class wv-6a0cab). --source and an
# explicit WV_CONFIG_DIR still choose.
if [ -z "${WV_CONFIG_DIR:-}" ] && [ -d "$SELF_DIR/../templates/procedures" ]; then
    SOURCE="$(cd "$SELF_DIR/../templates/procedures" && pwd)"
else
    SOURCE="${WV_CONFIG_DIR:-$HOME/.config/weave}/procedures"
fi
REPO="$(pwd)"
AGENT="all"
OUT=""
COPILOT_LINES=()
# AGENTS.md is universal: its index lists every shared, ready procedure,
# whatever adapters the procedure names (wv-6ef83b).
AGENTS_LINES=()
CODEX_IDS=()
CLAUDE_SKILLS=()
# .agents/skills/ is the harness-neutral skills surface: Codex, Amp and pi read
# it, Claude Code reads only .claude/skills/ (survey wv-279e7b,
# docs/findings/harness-capability-matrix-2026-11-17). Codex and Amp load it
# with no prompt and pi asks for folder trust because of it, so writing it is
# an opt-in a repository must ask for (owner decision on wv-cb5c96, ruling
# wv-2d8b49): it is written when --agent selects a harness that reads it
# (codex or all), or when the repository already holds a managed copy, which
# is the recorded opt-in, as a WEAVE PROCEDURES block is for AGENTS.md.
# .claude/skills/ stays the Claude Code adapter. Both are projections of the
# one procedure source, never a second source (wv-77586c).
NEUTRAL_SKILLS=()
# Marker line embedded in every generated SKILL.md. Its presence is the single
# signal distinguishing a Weave-managed skill (safe to refresh/remove) from a
# hand-written one (must never be overwritten or pruned).
CLAUDE_MARKER='<!-- WEAVE-MANAGED-SKILL: do not edit; regenerated by project-procedures.sh -->'

# Content-addressed provenance (wv-ef7ad7). Skills Weave shipped before the
# marker existed carry no marker, so a SKILL.md without it is either Weave's
# own earlier copy or a user's file. A file is Weave's if its bytes match a
# version Weave shipped under that same skill name: install.sh derives the
# list ("<sha256> <name>") from git history (gen-skill-provenance.sh). Such a
# copy is adopted and replaced; an edited copy, a hash shipped under another
# name, or a missing list leaves the refusal in place (fail closed).
SKILL_PROVENANCE="${WV_SKILL_PROVENANCE:-}"
if [ -z "$SKILL_PROVENANCE" ]; then
    for _p in "$SELF_DIR/skill-provenance.txt" "${WV_CONFIG_DIR:-$HOME/.config/weave}/skill-provenance.txt"; do
        [ -f "$_p" ] && { SKILL_PROVENANCE="$_p"; break; }
    done
fi
# The byte-identity test is shared with wv-init-repo's retired-skill removal
# (wv-853052): one implementation in wv-skill-retirement.sh.
SKILL_RETIREMENT_LIB="$SELF_DIR/lib/wv-skill-retirement.sh"
[ -f "$SKILL_RETIREMENT_LIB" ] || { echo "project-procedures: skill retirement helper missing: $SKILL_RETIREMENT_LIB" >&2; exit 1; }
# shellcheck source=scripts/lib/wv-skill-retirement.sh
source "$SKILL_RETIREMENT_LIB"
# weave_shipped_copy <skill name> <SKILL.md> — 0 when the file is byte-identical
# to a version Weave shipped under that name.
weave_shipped_copy() { wv_skill_shipped_copy "$1" "$2" "$SKILL_PROVENANCE"; }

for arg in "$@"; do
    case "$arg" in
        --source=*) SOURCE="${arg#*=}" ;;
        --repo=*) REPO="${arg#*=}" ;;
        --out=*) OUT="${arg#*=}" ;;
        # A comma list is what wv init-repo passes through (--agent=claude,codex).
        --agent=*) AGENT="${arg#*=}" ;;
        *) echo "Usage: $0 [--source=<dir>] [--repo=<dir>] [--out=<dir>] [--agent=claude|codex|copilot|all[,...]]" >&2; exit 2 ;;
    esac
done
_agent_tokens=$(printf '%s' "$AGENT" | tr ',' '\n')
while IFS= read -r _a; do
    case "$_a" in
        all|claude|codex|copilot) ;;
        *) echo "Usage: $0 [--source=<dir>] [--repo=<dir>] [--out=<dir>] [--agent=claude|codex|copilot|all[,...]]" >&2; exit 2 ;;
    esac
done <<< "$_agent_tokens"
# agent_selects <harness> — 0 when --agent names the harness or all.
agent_selects() { grep -qxE -- "all|$1" <<< "$_agent_tokens"; }
# The agent surfaces are written under OUT, the repository by default. wv doctor
# projects into a scratch copy of them and compares, so the projection format
# lives here only (wv-fc71f0).
OUT="${OUT:-$REPO}"
# NEUTRAL: whether this run owns .agents/skills (see NEUTRAL_SKILLS above).
# Decided once, before any write, so a prune cannot erase the opt-in mid-run.
NEUTRAL=false
if agent_selects codex || grep -rqsF -- 'WEAVE-MANAGED-SKILL' "$OUT/.agents/skills"; then
    NEUTRAL=true
fi

REPO_CLASS_LIB="$SELF_DIR/lib/wv-repository-class.sh"
[ -f "$REPO_CLASS_LIB" ] || { echo "project-procedures: repository classification helper missing: $REPO_CLASS_LIB" >&2; exit 1; }
# shellcheck source=scripts/lib/wv-repository-class.sh
source "$REPO_CLASS_LIB"
wv_repository_require_owned "$REPO" "procedure projection" || exit 1

# Validate the full contract set BEFORE mutating any consumer surface, so an
# invalid procedure aborts the run instead of silently pruning projections.
GEN="$SELF_DIR/gen-procedures.sh"
[ -x "$GEN" ] || { echo "project-procedures: validator not found at $GEN; refusing to project unvalidated contracts" >&2; exit 1; }
"$GEN" --source="$SOURCE" --check >/dev/null

# A repository may author its own procedures in .weave/procedures (delivery
# taxonomy R3, wv-fc71f0). The same contract validates them; they project into
# this repository only, and one with a package procedure's id replaces it here
# (owner and judge panel, docs/findings/judge-repo-procedures-2026-10-30/).
shopt -s nullglob
REPO_FILES=("$REPO/.weave/procedures"/*.md)
REPO_IDS=""
if [ "${#REPO_FILES[@]}" -gt 0 ]; then
    "$GEN" --source="$REPO/.weave/procedures" --check >/dev/null
    REPO_IDS=$(awk -F': *' 'FNR == 1 { seen = 0 } /^id:/ && !seen { print $2; seen = 1 }' "${REPO_FILES[@]}")
fi
PROCEDURES=()
for procedure in "$SOURCE"/*.md; do
    grep -qxF -- "$(awk -F': *' '/^id:/{print $2; exit}' "$procedure")" <<< "$REPO_IDS" || PROCEDURES+=("$procedure")
done
PROCEDURES+=("${REPO_FILES[@]}")
# Each source checks its own skill names; the combined set must too, or two
# procedures would write one skill directory.
if [ "${#PROCEDURES[@]}" -gt 0 ]; then
    dupes=$(awk -F': *' '/^claude_skill:/{print $2}' "${PROCEDURES[@]}" | sort | uniq -d)
    [ -z "$dupes" ] || { echo "project-procedures: claude_skill shared by a repository and a package procedure: $(echo "$dupes" | tr '\n' ' ')" >&2; exit 1; }
fi

# Exact-token adapter membership (validated to claude|codex|copilot above), so
# a value like 'notcodex' never matches by substring.
adapter_has() { # adapters-value token
    local t
    while IFS= read -r t; do [ "$t" = "$2" ] && return 0; done < <(echo "$1" | tr -d '[]' | tr ',' '\n' | sed 's/[[:space:]]//g')
    return 1
}

# Sparse, narrowing-only visibility override: ids under [local] in the target
# repo's config are force-demoted to local (kept out of projected surfaces).
# Only a [local] section is honored, so widening (local -> shared) is impossible.
OVERRIDE_LOCAL=""
if [ -f "$REPO/.weave/procedures-visibility.conf" ]; then
    OVERRIDE_LOCAL=$(awk '
        /^\[local\]/ { inside=1; next }
        /^\[/ { inside=0 }
        inside { sub(/#.*/, ""); gsub(/[[:space:]]/, ""); if ($0 != "") print }
    ' "$REPO/.weave/procedures-visibility.conf")
fi

# skill_collides <skill_md> <skill name> — 0 when SKILL_MD is hand-written: it
# exists, lacks the marker, and is not an unedited copy Weave shipped.
skill_collides() {
    [ -f "$1" ] && ! grep -qF -- "$CLAUDE_MARKER" "$1" && ! weave_shipped_copy "$2" "$1"
}

# write_skill_dir <skill_dir> <skill name> <procedure file> <description> <body>
# — stage the generated SKILL.md and the procedure's resources beside SKILL_DIR,
# then swap them in by rename, so the live projection survives a copy failure.
write_skill_dir() {
    local skill_dir="$1" skill_name="$2" file="$3" description="$4" body="$5"
    local staging resource executable parent rollback copy_ok=true
    parent="$(dirname "$skill_dir")"
    mkdir -p "$parent"
    # Stage under the destination parent (same filesystem) so the final swap is
    # an atomic rename and the live projection survives a copy failure.
    staging=$(mktemp -d "$parent/.weave-staging.XXXXXX")
    # A YAML double-quoted scalar. Written bare, a description holding ': '
    # is not YAML, and a strict parser drops every field (wv-ed1dbb).
    local yaml_description=${description//\\/\\\\}
    yaml_description=${yaml_description//\"/\\\"}
    printf '%s\n' '---' "name: $skill_name" "description: \"$yaml_description\"" '---' '' "$CLAUDE_MARKER" '' "$body" > "$staging/SKILL.md"
    while IFS='|' read -r resource executable; do
        [ -n "$resource" ] || continue
        cp "$(dirname "$file")/$resource" "$staging/$(basename "$resource")" || { copy_ok=false; break; }
        if [ "$executable" = true ]; then chmod +x "$staging/$(basename "$resource")"; else chmod -x "$staging/$(basename "$resource")"; fi
    done < <(awk '
        function flush() { if (path != "") { print path "|" exe; path="" } }
        NR > 1 && /^---$/{exit}
        /^resources:/{inside=1; next}
        inside && /^[a-z_]+:/{flush(); inside=0}
        inside && /^[[:space:]]*-[[:space:]]*path:/{flush(); sub(/.*path:[[:space:]]*/, ""); path=$0; exe="false"}
        inside && /^[[:space:]]*executable:/{sub(/.*executable:[[:space:]]*/, ""); exe=$0}
        END{flush()}
    ' "$file")
    if [ "$copy_ok" != true ]; then rm -rf "$staging"; echo "resource copy failed for skill '$skill_name'" >&2; return 1; fi
    # Atomic-ish swap: rename the old managed dir aside, move the new one in,
    # then drop the old. The live dir is replaced by a single rename.
    rollback=""
    if [ -d "$skill_dir" ]; then rollback="$parent/.weave-old.$skill_name.$$"; mv "$skill_dir" "$rollback"; fi
    if ! mv "$staging" "$skill_dir"; then
        [ -n "$rollback" ] && mv "$rollback" "$skill_dir"
        rm -rf "$staging"
        echo "failed to install staged skill '$skill_name' in $parent" >&2
        return 1
    fi
    if [ -n "$rollback" ]; then rm -rf "$rollback"; fi
}

project_one() {
    local file="$1" id description fallback adapters claude_skill body tmp
    id=$(awk -F': *' '/^id:/{print $2; exit}' "$file")
    description=$(awk '
        /^description:/ { v=$0; sub(/^description:[[:space:]]*/, "", v); inside=1; next }
        inside {
            if ($0 ~ /^[a-z_]+:/ || $0 ~ /^---$/) { inside=0; next }
            line=$0; sub(/^[[:space:]]+/, "", line)
            v=(v=="" ? line : v" "line)
        }
        END { print v }
    ' "$file" | tr -d '"')
    fallback=$(awk -F': *' '/^fallback:/{print $2; exit}' "$file" | tr -d '"')
    adapters=$(awk -F': *' '/^adapters:/{print $2; exit}' "$file")
    claude_skill=$(awk -F': *' '/^claude_skill:/{print $2; exit}' "$file")
    # Visibility gate: only shared procedures project into consumer adapter surfaces.
    # Default is local (opt-in to shipping); narrowing override can demote shared -> local.
    local visibility status
    visibility=$(awk -F': *' '/^visibility:/{print $2; exit}' "$file")
    visibility=${visibility:-local}
    if [ "$visibility" = shared ] && grep -qxF -- "$id" <<< "$OVERRIDE_LOCAL"; then
        visibility=local
    fi
    [ "$visibility" = shared ] || return 0
    # Draft procedures are shared-in-intent but not yet populated; never project
    # a placeholder shell into a consumer surface. A prior shared->draft demotion
    # is pruned by the stale-removal passes (codex managed flag, claude marker).
    status=$(awk -F': *' '/^status:/{print $2; exit}' "$file")
    [ "${status:-ready}" = ready ] || return 0
    body=$(awk 'BEGIN{n=0} /^---$/{n++; next} n>=2{print}' "$file")
    AGENTS_LINES+=("- $id — $description: $fallback")
    local do_claude=false do_codex=false do_copilot=false
    if adapter_has "$adapters" claude && agent_selects claude; then do_claude=true; fi
    if adapter_has "$adapters" codex && agent_selects codex; then do_codex=true; fi
    if adapter_has "$adapters" copilot && agent_selects copilot; then do_copilot=true; fi

    # Collision preflight — decide BEFORE mutating any adapter surface for this
    # procedure, so a hand-authored artifact is never partially overwritten.
    local skill_dir="$OUT/.claude/skills/$claude_skill" skill_md
    local neutral_dir="$OUT/.agents/skills/$claude_skill"
    skill_md="$skill_dir/SKILL.md"
    if [ "$do_claude" = true ] && [ -f "$skill_md" ] && ! grep -qF -- "$CLAUDE_MARKER" "$skill_md"; then
        if weave_shipped_copy "$claude_skill" "$skill_md"; then
            echo "procedure $id: adopting skill '$claude_skill': the file is a version Weave shipped, unedited"
        else
            echo "procedure $id: refusing to overwrite hand-written skill '$claude_skill'" >&2
            return 1
        fi
    fi
    if [ "$NEUTRAL" = true ] && [ -n "$claude_skill" ] && skill_collides "$neutral_dir/SKILL.md" "$claude_skill"; then
        echo "procedure $id: refusing to overwrite hand-written skill '.agents/skills/$claude_skill'" >&2
        return 1
    fi
    if [ "$do_codex" = true ] && [ -f "$OUT/.codex/weave.json" ] \
        && [ "$(jq --arg id "$id" '[.procedures[]? | select(.id == $id and (.managed != true))] | length' "$OUT/.codex/weave.json")" != 0 ]; then
        echo "procedure $id: refusing to overwrite hand-authored Codex entry '$id'" >&2
        return 1
    fi

    if [ "$do_claude" = true ]; then
        write_skill_dir "$skill_dir" "$claude_skill" "$file" "$description" "$body" \
            || { echo "procedure $id: Claude skill projection failed" >&2; return 1; }
        CLAUDE_SKILLS+=("$claude_skill")
    fi
    if [ "$NEUTRAL" = true ] && [ -n "$claude_skill" ]; then
        write_skill_dir "$neutral_dir" "$claude_skill" "$file" "$description" "$body" \
            || { echo "procedure $id: neutral skill projection failed" >&2; return 1; }
        NEUTRAL_SKILLS+=("$claude_skill")
    fi
    if [ "$do_codex" = true ]; then
        CODEX_IDS+=("$id")
        mkdir -p "$OUT/.codex"
        [ -f "$OUT/.codex/weave.json" ] || printf '%s\n' '{"schema":"weave.codex.v1"}' > "$OUT/.codex/weave.json"
        tmp=$(mktemp)
        jq --arg id "$id" --arg description "$description" --arg fallback "$fallback" \
            '.procedures = ((.procedures // []) | map(select(.id != $id)) + [{id:$id,description:$description,fallback:$fallback,managed:true}])' \
            "$OUT/.codex/weave.json" > "$tmp"
        mv "$tmp" "$OUT/.codex/weave.json"
    fi
    if [ "$do_copilot" = true ]; then
        COPILOT_LINES+=("- $id — $description: $fallback")
    fi
}

# Check every targeted ownership boundary before the first projection write.
# A collision in a later procedure must not leave earlier Claude/Codex updates
# applied while Copilot/stale cleanup never runs.
preflight_one() {
    local file="$1" id adapters claude_skill visibility status skill_md
    id=$(awk -F': *' '/^id:/{print $2; exit}' "$file")
    adapters=$(awk -F': *' '/^adapters:/{print $2; exit}' "$file")
    claude_skill=$(awk -F': *' '/^claude_skill:/{print $2; exit}' "$file")
    visibility=$(awk -F': *' '/^visibility:/{print $2; exit}' "$file"); visibility=${visibility:-local}
    if [ "$visibility" = shared ] && grep -qxF -- "$id" <<< "$OVERRIDE_LOCAL"; then visibility=local; fi
    [ "$visibility" = shared ] || return 0
    status=$(awk -F': *' '/^status:/{print $2; exit}' "$file"); [ "${status:-ready}" = ready ] || return 0
    if adapter_has "$adapters" claude && agent_selects claude; then
        skill_md="$OUT/.claude/skills/$claude_skill/SKILL.md"
        if skill_collides "$skill_md" "$claude_skill"; then
            echo "procedure $id: refusing to overwrite hand-written skill '$claude_skill'" >&2
            return 1
        fi
    fi
    if [ "$NEUTRAL" = true ] && [ -n "$claude_skill" ] && skill_collides "$OUT/.agents/skills/$claude_skill/SKILL.md" "$claude_skill"; then
        echo "procedure $id: refusing to overwrite hand-written skill '.agents/skills/$claude_skill'" >&2
        return 1
    fi
    if adapter_has "$adapters" codex && agent_selects codex \
        && [ -f "$OUT/.codex/weave.json" ] \
        && [ "$(jq --arg id "$id" '[.procedures[]? | select(.id == $id and (.managed != true))] | length' "$OUT/.codex/weave.json")" != 0 ]; then
        echo "procedure $id: refusing to overwrite hand-authored Codex entry '$id'" >&2
        return 1
    fi
}

write_copilot_projection() {
    agent_selects copilot || return 0
    mkdir -p "$OUT/.github"
    local copilot="$OUT/.github/copilot-instructions.md" block
    block=$(printf '%s\n' '<!-- BEGIN WEAVE PROCEDURES -->' "${COPILOT_LINES[@]}" '<!-- END WEAVE PROCEDURES -->')
    if [ ! -f "$copilot" ]; then
        printf '%s\n' "$block" > "$copilot"
    elif grep -q 'BEGIN WEAVE PROCEDURES' "$copilot"; then
        awk -v block="$block" '
            /BEGIN WEAVE PROCEDURES/ { print block; skip=1; next }
            /END WEAVE PROCEDURES/ && skip { skip=0; next }
            !skip { print }
        ' "$copilot" > "$copilot.tmp"
        mv "$copilot.tmp" "$copilot"
    else
        printf '\n%s\n' "$block" >> "$copilot"
    fi
}

# AGENTS.md is user-owned in a consumer repository (04feaa432), so it opts in by
# marker: an existing WEAVE PROCEDURES block is refreshed; a file without one,
# or no file, is left alone. Runs for every --agent value, because AGENTS.md is
# the file any harness reads.
write_agents_projection() {
    local agents="$OUT/AGENTS.md" block
    [ -f "$agents" ] && grep -q 'BEGIN WEAVE PROCEDURES' "$agents" && grep -q 'END WEAVE PROCEDURES' "$agents" || return 0
    block=$(printf '%s\n' '<!-- BEGIN WEAVE PROCEDURES -->' "${AGENTS_LINES[@]}" '<!-- END WEAVE PROCEDURES -->')
    awk -v block="$block" '
        /BEGIN WEAVE PROCEDURES/ { print block; skip=1; next }
        /END WEAVE PROCEDURES/ && skip { skip=0; next }
        !skip { print }
    ' "$agents" > "$agents.tmp"
    mv "$agents.tmp" "$agents"
}

# Prune Weave-managed Codex entries (managed:true) that are no longer in the
# active set — a procedure deleted, demoted to local, or flipped to draft.
# Manually-authored entries (no managed flag) are always preserved.
remove_stale_codex_procedures() {
    agent_selects codex || return 0
    [ -f "$OUT/.codex/weave.json" ] || return 0
    local active tmp
    active=$(printf '%s\n' "${CODEX_IDS[@]:-}" | jq -R . | jq -s 'map(select(. != ""))')
    tmp=$(mktemp)
    jq --argjson active "$active" \
        '.procedures = ((.procedures // []) | map(.id as $pid | select((.managed != true) or (($active | index($pid)) != null))))' \
        "$OUT/.codex/weave.json" > "$tmp"
    mv "$tmp" "$OUT/.codex/weave.json"
}

# Prune Weave-managed skills (marker-bearing) that are no longer in the active
# shared set — a procedure deleted, demoted to local, or flipped to draft. Skills
# without the marker are hand-written and never touched.
# remove_stale_skills <skills root> <active name>... — drop marker-bearing skill
# directories under ROOT whose name is not in the active set.
remove_stale_skills() {
    local root="$1" dir name active
    shift
    [ -d "$root" ] || return 0
    active=$(printf '%s\n' "$@")
    for dir in "$root"/*/; do
        [ -f "$dir/SKILL.md" ] || continue
        grep -qF -- "$CLAUDE_MARKER" "$dir/SKILL.md" || continue
        name=$(basename "$dir")
        grep -qxF -- "$name" <<< "$active" || rm -rf "$dir"
    done
}

remove_stale_claude_procedures() {
    agent_selects claude || return 0
    remove_stale_skills "$OUT/.claude/skills" "${CLAUDE_SKILLS[@]:-}"
}

# The neutral surface is pruned only by a run that owns it (NEUTRAL).
remove_stale_neutral_skills() {
    [ "$NEUTRAL" = true ] || return 0
    remove_stale_skills "$OUT/.agents/skills" "${NEUTRAL_SKILLS[@]:-}"
}

for procedure in "${PROCEDURES[@]}"; do preflight_one "$procedure"; done
for procedure in "${PROCEDURES[@]}"; do project_one "$procedure"; done
remove_stale_codex_procedures
remove_stale_claude_procedures
remove_stale_neutral_skills
write_copilot_projection
write_agents_projection
